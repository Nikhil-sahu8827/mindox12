package com.substring.docmind.document.service.youtube;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.substring.docmind.document.dto.youtube.TranscriptSegmentDto;
import lombok.Builder;
import lombok.Data;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.jsoup.Jsoup;
import org.springframework.stereotype.Service;

import java.io.OutputStream;
import java.net.HttpURLConnection;
import java.net.URI;
import java.net.URL;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

@Slf4j
@Service
@RequiredArgsConstructor
public class YouTubeTranscriptService {

    private final ObjectMapper objectMapper = new ObjectMapper();

    private static final String INNERTUBE_API_URL = "https://www.youtube.com/youtubei/v1/player?prettyPrint=false";
    private static final String ANDROID_CLIENT_VERSION = "20.10.38";
    private static final String ANDROID_USER_AGENT = "com.google.android.youtube/" + ANDROID_CLIENT_VERSION + " (Linux; U; Android 14)";
    private static final String BROWSER_USER_AGENT = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36";

    @Data
    @Builder
    public static class ExtractionResult {
        private String videoId;
        private boolean success;
        private String captionLanguage;
        private boolean isAutoGenerated;
        private List<TranscriptSegmentDto> segments;
        private String fullTranscriptText;
        private String errorMessage;
    }

    public ExtractionResult extractTranscript(String videoId, String preferredLang) {
        log.info("Extracting complete transcript for videoId: {}, preferredLang: {}", videoId, preferredLang);

        // 1. Primary Engine: Android Innertube Client (Bypasses poToken & delivers 100% complete transcripts)
        try {
            ExtractionResult result = extractViaInnertube(videoId, preferredLang);
            if (result != null && result.isSuccess() && result.getSegments() != null && !result.getSegments().isEmpty()) {
                log.info("Successfully extracted {} transcript segments via Innertube for {}", result.getSegments().size(), videoId);
                return result;
            }
        } catch (Exception e) {
            log.warn("Innertube extraction notice for {}: {}", videoId, e.getMessage());
        }

        // 2. Secondary Engine: Web Page Scraping Fallback
        try {
            ExtractionResult webResult = extractViaWebPage(videoId, preferredLang);
            if (webResult != null && webResult.isSuccess() && webResult.getSegments() != null && !webResult.getSegments().isEmpty()) {
                log.info("Successfully extracted {} transcript segments via Web Scraping for {}", webResult.getSegments().size(), videoId);
                return webResult;
            }
        } catch (Exception e) {
            log.warn("Web scraping extraction notice for {}: {}", videoId, e.getMessage());
        }

        log.warn("No transcript or subtitles available for YouTube video {}", videoId);
        return ExtractionResult.builder()
                .videoId(videoId)
                .success(false)
                .segments(new ArrayList<>())
                .fullTranscriptText("")
                .errorMessage("No captions or transcript tracks available for this video.")
                .build();
    }

    private ExtractionResult extractViaInnertube(String videoId, String preferredLang) throws Exception {
        String payloadJson = String.format(
                "{\"context\":{\"client\":{\"clientName\":\"ANDROID\",\"clientVersion\":\"%s\"}},\"videoId\":\"%s\"}",
                ANDROID_CLIENT_VERSION, videoId
        );

        URL url = URI.create(INNERTUBE_API_URL).toURL();
        HttpURLConnection conn = (HttpURLConnection) url.openConnection();
        conn.setRequestMethod("POST");
        conn.setConnectTimeout(15000);
        conn.setReadTimeout(20000);
        conn.setDoOutput(true);
        conn.setRequestProperty("Content-Type", "application/json");
        conn.setRequestProperty("User-Agent", ANDROID_USER_AGENT);

        try (OutputStream os = conn.getOutputStream()) {
            os.write(payloadJson.getBytes(StandardCharsets.UTF_8));
        }

        int statusCode = conn.getResponseCode();
        if (statusCode != 200) {
            log.debug("Innertube HTTP status {} for {}", statusCode, videoId);
            return null;
        }

        String responseBody = new String(conn.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
        JsonNode root = objectMapper.readTree(responseBody);
        JsonNode captionTracksNode = root.path("captions").path("playerCaptionsTracklistRenderer").path("captionTracks");

        if (!captionTracksNode.isArray() || captionTracksNode.isEmpty()) {
            return null;
        }

        return processCaptionTracks(captionTracksNode, videoId, preferredLang);
    }

    private ExtractionResult extractViaWebPage(String videoId, String preferredLang) throws Exception {
        String watchUrl = "https://www.youtube.com/watch?v=" + videoId;
        org.jsoup.nodes.Document doc = Jsoup.connect(watchUrl)
                .userAgent(BROWSER_USER_AGENT)
                .header("Accept-Language", preferredLang != null ? preferredLang : "en-US,en;q=0.9")
                .timeout(15000)
                .get();

        String html = doc.html();
        JsonNode playerResponse = parseInlinePlayerResponse(html);
        if (playerResponse == null) {
            return null;
        }

        JsonNode captionTracksNode = playerResponse.path("captions").path("playerCaptionsTracklistRenderer").path("captionTracks");
        if (!captionTracksNode.isArray() || captionTracksNode.isEmpty()) {
            return null;
        }

        return processCaptionTracks(captionTracksNode, videoId, preferredLang);
    }

    private ExtractionResult processCaptionTracks(JsonNode captionTracksNode, String videoId, String preferredLang) throws Exception {
        JsonNode chosenTrack = null;

        // Try exact preferred language
        if (preferredLang != null && !preferredLang.isBlank()) {
            for (JsonNode track : captionTracksNode) {
                if (track.path("languageCode").asText("").equalsIgnoreCase(preferredLang.trim())) {
                    chosenTrack = track;
                    break;
                }
            }
        }

        // Try manual caption first (no "kind": "asr")
        if (chosenTrack == null) {
            for (JsonNode track : captionTracksNode) {
                if (!"asr".equalsIgnoreCase(track.path("kind").asText(""))) {
                    chosenTrack = track;
                    break;
                }
            }
        }

        // Default to first track
        if (chosenTrack == null && !captionTracksNode.isEmpty()) {
            chosenTrack = captionTracksNode.get(0);
        }

        if (chosenTrack == null) {
            return null;
        }

        String baseUrl = chosenTrack.path("baseUrl").asText();
        String lang = chosenTrack.path("languageCode").asText("en");
        boolean isAutoGenerated = "asr".equalsIgnoreCase(chosenTrack.path("kind").asText(""));

        if (baseUrl.isBlank()) {
            return null;
        }

        // Fetch caption XML directly
        URL capUrl = URI.create(baseUrl).toURL();
        HttpURLConnection capConn = (HttpURLConnection) capUrl.openConnection();
        capConn.setRequestMethod("GET");
        capConn.setConnectTimeout(15000);
        capConn.setReadTimeout(20000);
        capConn.setRequestProperty("User-Agent", BROWSER_USER_AGENT);

        int capStatus = capConn.getResponseCode();
        if (capStatus != 200) {
            log.debug("Caption track HTTP status {} for {}", capStatus, videoId);
            return null;
        }

        String xml = new String(capConn.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
        if (xml.isBlank()) {
            return null;
        }

        List<TranscriptSegmentDto> segments = parseXml(xml, lang);
        if (segments.isEmpty()) {
            return null;
        }

        StringBuilder fullText = new StringBuilder();
        for (TranscriptSegmentDto seg : segments) {
            fullText.append("[").append(seg.getTimestamp()).append("] ").append(seg.getText()).append("\n");
        }

        return ExtractionResult.builder()
                .videoId(videoId)
                .success(true)
                .captionLanguage(lang)
                .isAutoGenerated(isAutoGenerated)
                .segments(segments)
                .fullTranscriptText(fullText.toString().trim())
                .build();
    }

    public List<TranscriptSegmentDto> parseXml(String xml, String lang) {
        List<TranscriptSegmentDto> results = new ArrayList<>();

        // Try srv3 format: <p t="ms" d="ms"><s>word</s>...</p>
        Pattern pPattern = Pattern.compile("<p\\s+t=\"(\\d+)\"\\s+d=\"(\\d+)\"[^>]*>([\\s\\S]*?)</p>");
        Matcher pMatcher = pPattern.matcher(xml);

        Pattern sPattern = Pattern.compile("<s[^>]*>([^<]*)</s>");

        while (pMatcher.find()) {
            long startMs = Long.parseLong(pMatcher.group(1));
            long durMs = Long.parseLong(pMatcher.group(2));
            String inner = pMatcher.group(3);

            StringBuilder textBuilder = new StringBuilder();
            Matcher sMatcher = sPattern.matcher(inner);
            while (sMatcher.find()) {
                textBuilder.append(sMatcher.group(1));
            }

            String text = textBuilder.toString();
            if (text.isBlank()) {
                text = inner.replaceAll("<[^>]+>", "");
            }

            text = decodeHtmlEntities(text).trim();
            if (!text.isEmpty()) {
                results.add(TranscriptSegmentDto.builder()
                        .startMs(startMs)
                        .durationMs(durMs)
                        .timestamp(formatTimeMs(startMs))
                        .text(text)
                        .lang(lang)
                        .build());
            }
        }

        if (!results.isEmpty()) {
            return results;
        }

        // Fall back to classic format: <text start="s" dur="s">content</text>
        Pattern textPattern = Pattern.compile("<text\\s+start=\"([^\"]*)\"\\s+dur=\"([^\"]*)\"[^>]*>([\\s\\S]*?)</text>");
        Matcher textMatcher = textPattern.matcher(xml);

        while (textMatcher.find()) {
            try {
                double startSec = Double.parseDouble(textMatcher.group(1));
                double durSec = Double.parseDouble(textMatcher.group(2));
                String rawText = textMatcher.group(3);
                String text = decodeHtmlEntities(rawText).trim();

                if (!text.isEmpty()) {
                    long startMs = (long) (startSec * 1000);
                    long durMs = (long) (durSec * 1000);
                    results.add(TranscriptSegmentDto.builder()
                            .startMs(startMs)
                            .durationMs(durMs)
                            .timestamp(formatTimeMs(startMs))
                            .text(text)
                            .lang(lang)
                            .build());
                }
            } catch (Exception ignored) {}
        }

        return results;
    }

    private JsonNode parseInlinePlayerResponse(String html) {
        String token = "var ytInitialPlayerResponse = ";
        int idx = html.indexOf(token);
        if (idx == -1) {
            token = "ytInitialPlayerResponse = ";
            idx = html.indexOf(token);
        }
        if (idx == -1) return null;

        int start = idx + token.length();
        int depth = 0;
        for (int i = start; i < html.length(); i++) {
            char c = html.charAt(i);
            if (c == '{') depth++;
            else if (c == '}') {
                depth--;
                if (depth == 0) {
                    try {
                        return objectMapper.readTree(html.substring(start, i + 1));
                    } catch (Exception e) {
                        return null;
                    }
                }
            }
        }
        return null;
    }

    public static String formatTimeMs(long ms) {
        long totalSeconds = ms / 1000;
        long hours = totalSeconds / 3600;
        long minutes = (totalSeconds % 3600) / 60;
        long seconds = totalSeconds % 60;
        if (hours > 0) {
            return String.format("%02d:%02d:%02d", hours, minutes, seconds);
        } else {
            return String.format("%02d:%02d", minutes, seconds);
        }
    }

    public static String decodeHtmlEntities(String text) {
        if (text == null) return "";
        return text
                .replace("&amp;", "&")
                .replace("&lt;", "<")
                .replace("&gt;", ">")
                .replace("&quot;", "\"")
                .replace("&#39;", "'")
                .replace("&apos;", "'")
                .replaceAll("&#(\\d+);", "")
                .replaceAll("\\s+", " ");
    }
}
